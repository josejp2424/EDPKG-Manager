void ai_select_language(void) {
    const char *e = g_getenv("LC_ALL");
    if (!e || !*e) e = g_getenv("LC_MESSAGES");
    if (!e || !*e) e = g_getenv("LANG");
    if (!e) return;
    char code[8] = {0};
    size_t n = strcspn(e, "_.@-");
    if (n == 0 || n >= sizeof(code)) return;
    for (size_t i = 0; i < n; i++) code[i] = g_ascii_tolower(e[i]);
    for (guint i = 0; i < G_N_ELEMENTS(langs); i++) if (strcmp(code, langs[i].code) == 0) { current = &langs[i]; return; }
}
const char *ai_tr(AiKey key) { return (key >= 0 && key < AI_T_COUNT) ? current->value[key] : ""; }
